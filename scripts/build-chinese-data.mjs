#!/usr/bin/env node
// Generate a character lookup table without loading a converter in QuickJS.
// Vendored dictionary: BYVoid/OpenCC ver.1.1.9, Apache-2.0.
// Source commit: 556ed22496d650bd0b13b6c163be9814637970ae
// https://github.com/BYVoid/OpenCC/blob/556ed22496d650bd0b13b6c163be9814637970ae/data/dictionary/TSCharacters.txt

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const VENDOR_DIR = join(ROOT, 'scripts', 'vendor', 'opencc');
const OUT_DIR = join(ROOT, 'src', 'data');
const mappings = new Map();

for (const line of readFileSync(join(VENDOR_DIR, 'TSCharacters.txt'), 'utf8').split(/\r?\n/)) {
  if (!line.trim() || line.startsWith('#')) continue;
  const [traditional, candidates] = line.split('\t');
  const simplified = candidates?.split(' ')[0];
  if (Array.from(traditional).length !== 1 || !simplified || Array.from(simplified).length !== 1) {
    throw new Error(`Invalid OpenCC character entry: ${line}`);
  }
  // Use the first candidate, following the dictionary's default conversion.
  // This folds spellings for matching; it is not phrase-aware display conversion.
  if (traditional !== simplified) mappings.set(traditional, simplified);
}

// Resolve chained variants at build time so normalization is idempotent.
// For example, 薴 -> 苧 -> 苎 must give all three spellings the same key.
const entries = [...mappings].map(([traditional, simplified]) => {
  const seen = new Set([traditional]);
  while (mappings.has(simplified)) {
    if (seen.has(simplified)) throw new Error(`Cyclic OpenCC character entry: ${traditional}`);
    seen.add(simplified);
    simplified = mappings.get(simplified);
  }
  return [traditional, simplified];
});

const attribution = [
  'OpenCC TSCharacters dictionary, ver.1.1.9 (Apache-2.0).',
  'OpenCC contributors (BYVoid/OpenCC).',
  'Source commit: 556ed22496d650bd0b13b6c163be9814637970ae',
  'https://github.com/BYVoid/OpenCC',
  'Derived character map uses the first candidate and resolves chained variants.',
].join('\n');

const lines = [
  '// AUTO-GENERATED by scripts/build-chinese-data.mjs - DO NOT EDIT',
  '/*!',
  attribution,
  readFileSync(join(VENDOR_DIR, 'LICENSE'), 'utf8').trimEnd(),
  '*/',
  '',
  'export const traditionalToSimplifiedMap: Record<string, string> = {',
  ...entries.map(([traditional, simplified]) => `  ${JSON.stringify(traditional)}: ${JSON.stringify(simplified)},`),
  '};',
  '',
];

mkdirSync(OUT_DIR, { recursive: true });
writeFileSync(join(OUT_DIR, 'traditional-to-simplified-map.ts'), lines.join('\n'));
console.log(`[build-chinese-data] wrote static character map (${entries.length} chars) with OpenCC license`);
