async function harness(run, { multi = false, saved = [] } = {}) {
  const originals = { songloft: globalThis.songloft, fetch: globalThis.fetch, crypto: Object.getOwnPropertyDescriptor(globalThis, 'crypto'), now: Date.now, setTimeout, clearTimeout };
  let now = 100000, nextTimer = 0, nextSocket = 0, receive, released, external = false;
  const timers = new Map(), storage = new Map(saved), packets = [], calls = [], notifications = [], closed = [], warnings = [], bound = [];
  const service = {
    stopPlay: async (...args) => { calls.push(['stop', ...args]); return true; },
    playURL: async (...args) => { calls.push(['play', ...args]); return true; },
    pausePlayVerified: async (...args) => { calls.push(['pause', ...args]); return 'paused'; },
    resumePlay: async (...args) => { calls.push(['resume', ...args]); return true; },
    setVolume: async (...args) => { calls.push(['volume', ...args]); return true; },
    getVolume: async () => 40,
    getPlayState: async () => ({ status: 1, position: 12, duration: 100, hasPosition: true }),
  };
  const manager = {
    beginExternalPlayback: async callback => { external = true; released = callback; return true; },
    endExternalPlayback: () => { external = false; released?.(); },
    runExternalPlayback: async action => { assert.equal(external, true); return action(); },
  };
  const accounts = [{ id: 'a', devices: [{ device_id: 'd', device_name: '客厅', managed: true }] }];
  const configs = { getAccounts: async () => accounts, getDevices: async id => accounts.find(a => a.id === id)?.devices || [], getDeviceGroups: async () => [] };
  const managers = new Map([['a/d', manager]]);
  const players = {
    getOrCreate: async (a, d) => {
      const key = a + '/' + d;
      if (!managers.has(key)) {
        let owns = false, release;
        managers.set(key, {
          beginExternalPlayback: async callback => { owns = true; release = callback; return true; },
          endExternalPlayback: () => { owns = false; release?.(); },
          runExternalPlayback: async action => { assert.equal(owns, true); return action(); },
        });
      }
      return managers.get(key);
    }
  };
  globalThis.songloft = {
    storage: { get: async k => storage.get(k), set: async (k, v) => storage.set(k, v) },
    net: {
      udpBind: async options => { assert.equal(options.reuseAddress, true); const socketId = `s${++nextSocket}`; bound.push(socketId); return { socketId }; },
      udpJoinMulticast: async () => { }, onData: (_id, handler) => { receive = handler; },
      udpSend: async (_id, data, address) => { packets.push({ data, address }); },
      udpClose: async id => { closed.push(id); },
    }, log: { warn(message) { warnings.push(message); }, info() { } },
  };
  Object.defineProperty(globalThis, 'crypto', { configurable: true, value: { randomBytes } });
  globalThis.fetch = async (url, options) => { notifications.push({ url, ...options }); return { ok: true }; };
  Date.now = () => now;
  globalThis.setTimeout = (fn, delay) => { const id = ++nextTimer; timers.set(id, { at: now + delay, fn }); return id; };
  globalThis.clearTimeout = id => timers.delete(id);
  const receiver = multi ? new DLNAReceivers(configs, service, players) : new DLNAReceiver(configs, service, players, UUID, new SSDPDiscovery());
  if (multi) await receiver.init();
  const req = (method, path, headers = {}, body = '') => receiver.handle({ method, path, headers, body, query: '', remoteAddr: '192.168.1.3:12345' });
  const soap = (action, args = {}, serviceName = 'AVTransport') => req('POST', `${ROOT}/${serviceName}/control`, { SOAPACTION: `"${TYPES[serviceName]}#${action}"` }, `<s:Envelope xmlns:s="http://schemas.xmlsoap.org/soap/envelope/"><s:Body><u:${action} xmlns:u="${TYPES[serviceName]}">${Object.entries(args).map(([k, v]) => `<${k}>${escapeXML(v)}</${k}>`).join('')}</u:${action}></s:Body></s:Envelope>`);
  const advance = async ms => {
    const end = now + ms;
    while (true) {
      const entry = [...timers.entries()].filter(([, t]) => t.at <= end).sort((a, b) => a[1].at - b[1].at)[0];
      if (!entry) break;
      now = entry[1].at; timers.delete(entry[0]); entry[1].fn(); await flush();
    }
    now = end; await flush();
  };
  try { await run({ receiver, req, soap, advance, packets, calls, notifications, closed, warnings, bound, timers, storage, service, configs, accounts, manager, managers, players, search: message => receive({ data: btoa(message), remoteAddr: '192.168.1.3:54321' }) }); }
  finally {
    await receiver.close();
    globalThis.songloft = originals.songloft; globalThis.fetch = originals.fetch;
    if (originals.crypto) Object.defineProperty(globalThis, 'crypto', originals.crypto); else delete globalThis.crypto;
    Date.now = originals.now; globalThis.setTimeout = originals.setTimeout; globalThis.clearTimeout = originals.clearTimeout;
  }
}

