function scoped(h, receiver) {
  return async (action, args = {}, service = 'AVTransport') => h.req('POST', `/dlna/${receiver.id}/${service}/control`,
    { SOAPAction: `"${TYPES[service]}#${action}"` },
    `<s:Envelope xmlns:s="http://schemas.xmlsoap.org/soap/envelope/"><s:Body><u:${action} xmlns:u="${TYPES[service]}">${Object.entries(args).map(([k, v]) => `<${k}>${escapeXML(v)}</${k}>`).join('')}</u:${action}></s:Body></s:Envelope>`);
}
